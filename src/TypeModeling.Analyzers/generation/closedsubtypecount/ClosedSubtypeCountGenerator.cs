using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using TypeModeling.Analyzers.Facts;

namespace TypeModeling.Analyzers.Generation.ClosedSubtypeCount;

/// <summary>閉じた class ごとの直接の派生の数を assembly 属性として残す generator</summary>
[Generator]
public sealed class ClosedSubtypeCountGenerator : IIncrementalGenerator
{
    /// <summary>生成 source の hint 名</summary>
    private const string HintName = "TypeModeling.ClosedSubtypeCount.g.cs";

    /// <summary>compilation から派生の数の属性を作る pipeline の登録</summary>
    /// <param name="context">incremental generator の初期化 context</param>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var source = context.CompilationProvider.Select(static (compilation, _) => Source(compilation));
        context.RegisterSourceOutput(source, static (production, text) => production.AddSource(HintName, text));
    }

    /// <summary>compilation の閉じた class ごとの派生の数の属性</summary>
    /// <param name="compilation">数える compilation</param>
    /// <returns>assembly 属性の source</returns>
    private static string Source(Compilation compilation)
    {
        var lines = ClosedSubtypes.DeclaredTypes(compilation.Assembly)
            .Where(type => ClosedTypeSet.IsClosedClass(type) && IsPublic(type))
            .Select(closed => (Name: Typeof(closed), Count: DirectSubtypeCount(closed, compilation)))
            .OrderBy(entry => entry.Name, System.StringComparer.Ordinal)
            .Select(entry => $"[assembly: global::TypeModeling.Domain.ClosedSubtypeCount(typeof({entry.Name}), {entry.Count})]")
            .ToArray();
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        foreach (var line in lines)
            builder.AppendLine(line);

        return builder.ToString();
    }

    /// <summary>同じ compilation で数えた直接の派生の数</summary>
    /// <param name="closed">閉じた class</param>
    /// <param name="compilation">数える compilation</param>
    /// <returns>直接の派生の数</returns>
    private static int DirectSubtypeCount(INamedTypeSymbol closed, Compilation compilation)
    {
        _ = ClosedSubtypes.TryGetDirectSubtypeDefinitions(closed, compilation, out var subtypes);
        return subtypes.Length;
    }

    /// <summary>別の assembly から見える型かの判定</summary>
    /// <param name="type">判定する型</param>
    /// <returns>型と外側の型が全て public なら true</returns>
    private static bool IsPublic(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.ContainingType)
        {
            if (current.DeclaredAccessibility != Accessibility.Public)
                return false;
        }

        return true;
    }

    /// <summary>typeof に書く開いた型の名前</summary>
    /// <param name="type">閉じた class</param>
    /// <returns>generic の型引数を空けた完全修飾の名前</returns>
    private static string Typeof(INamedTypeSymbol type)
    {
        var own = Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(type.Name) == Microsoft.CodeAnalysis.CSharp.SyntaxKind.None
            ? type.Name
            : "@" + type.Name;
        if (type.Arity > 0)
            own += "<" + new string(',', type.Arity - 1) + ">";

        if (type.ContainingType is { } container)
            return Typeof(container) + "." + own;

        return type.ContainingNamespace.IsGlobalNamespace ? "global::" + own : $"global::{type.ContainingNamespace.ToDisplayString()}.{own}";
    }
}

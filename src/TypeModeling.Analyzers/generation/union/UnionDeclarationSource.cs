using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace TypeModeling.Analyzers.Generation.Union;

/// <summary>union 宣言の形の型への、C# 15 の lowering と同じ member の source</summary>
internal static class UnionDeclarationSource
{
    /// <summary>引数の型を書く、nullable の注釈を保つ完全修飾の書式</summary>
    private static readonly SymbolDisplayFormat ParameterTypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    /// <summary>union 宣言の形の型の生成 source</summary>
    /// <param name="type">union 型</param>
    /// <param name="declaration">union 型の宣言のうち属性を持つもの</param>
    /// <returns>hint 名と source。生成できない形なら null</returns>
    internal static GeneratedUnion? Build(INamedTypeSymbol type, TypeDeclarationSyntax declaration)
    {
        var constructors = UnionDeclarationShape.CaseConstructors(type)
            .Where(constructor => constructor.PartialImplementationPart is null)
            .ToArray();
        if (constructors.Length == 0 || !AllContainersArePartial(type))
            return null;

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        if (!type.ContainingNamespace.IsGlobalNamespace)
            builder.AppendLine($"namespace {type.ContainingNamespace.ToDisplayString()};");

        var containers = Containers(type);
        foreach (var container in containers)
            builder.AppendLine($"partial {Keyword(container)} {Name(container)}").AppendLine("{");

        builder.AppendLine($"partial {Keyword(type)} {Name(type)} : global::System.Runtime.CompilerServices.IUnion").AppendLine("{");
        AppendMembers(builder, type, constructors, UnionDeclarationShape.LanguageHasUnions(declaration.SyntaxTree));
        builder.AppendLine("}");
        foreach (var _ in containers)
            builder.AppendLine("}");

        var hintName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
            .Replace("global::", "").Replace('<', '[').Replace('>', ']') + ".Union.g.cs";
        return new GeneratedUnion(hintName, builder.ToString());
    }

    /// <summary>Value、union 構築子の本体、暗黙の変換の追記</summary>
    /// <param name="builder">source の書き込み先</param>
    /// <param name="type">union 型</param>
    /// <param name="constructors">実装を足す partial コンストラクタ</param>
    /// <param name="languageHasUnions">言語が union 変換を持つ場合に true</param>
    private static void AppendMembers(StringBuilder builder, INamedTypeSymbol type, IMethodSymbol[] constructors, bool languageHasUnions)
    {
        var caseTypes = constructors.Select(constructor => constructor.Parameters[0].Type).ToArray();
        var valueType = caseTypes.Any(CanBeNull) ? "object?" : "object";
        builder.AppendLine("    /// <summary>union が持つ case の値</summary>");
        builder.AppendLine($"    public {valueType} Value {{ get; }}");
        foreach (var constructor in constructors)
        {
            var parameter = constructor.Parameters[0];
            var modifier = parameter.RefKind == RefKind.In ? "in " : "";
            builder.AppendLine();
            builder.AppendLine("    /// <summary>case の値を持つ union の構築</summary>");
            builder.AppendLine($"    /// <param name=\"{parameter.Name}\">union が持つ case の値</param>");
            builder.AppendLine($"    {Accessibility(constructor)} partial {type.Name}({modifier}{parameter.Type.ToDisplayString(ParameterTypeFormat)} {Escape(parameter.Name)}) => this.Value = {Escape(parameter.Name)};");
        }

        if (languageHasUnions)
            return;

        foreach (var caseType in caseTypes.Where(caseType => AllowsConversion(type, caseType)))
        {
            builder.AppendLine();
            builder.AppendLine("    /// <summary>C# 15 の union 変換に当たる case の値からの暗黙の変換</summary>");
            builder.AppendLine("    /// <param name=\"value\">union が持つ case の値</param>");
            builder.AppendLine("    /// <returns>case の値を持つ union</returns>");
            builder.AppendLine($"    public static implicit operator {Name(type)}({caseType.ToDisplayString(ParameterTypeFormat)} value) => new(value);");
        }
    }

    /// <summary>case 型の値が null になりうるかの判定</summary>
    /// <param name="type">case 型</param>
    /// <remarks>struct と unmanaged の制約を持つ型引数は値型として最初の分岐で扱う</remarks>
    /// <returns>null を取りうる場合に true</returns>
    private static bool CanBeNull(ITypeSymbol type) => type switch
    {
        { IsValueType: true } => type.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T,
        ITypeParameterSymbol parameter => !parameter.HasNotNullConstraint,
        _ => type.NullableAnnotation != NullableAnnotation.NotAnnotated,
    };

    /// <summary>case 型からの暗黙の変換を宣言できるかの判定</summary>
    /// <param name="union">union 型</param>
    /// <param name="caseType">case 型</param>
    /// <returns>言語が利用者定義の変換を許す case 型なら true</returns>
    private static bool AllowsConversion(INamedTypeSymbol union, ITypeSymbol caseType) =>
        caseType.TypeKind != TypeKind.Interface &&
        caseType.SpecialType is not (SpecialType.System_Object or SpecialType.System_ValueType) &&
        !SymbolEqualityComparer.Default.Equals(caseType, union) &&
        !union.GetMembers(WellKnownMemberNames.ImplicitConversionName)
            .OfType<IMethodSymbol>()
            .Any(conversion => SymbolEqualityComparer.Default.Equals(conversion.Parameters[0].Type, caseType));

    /// <summary>外側から並べた、入れ子の外側の型</summary>
    /// <param name="type">入れ子の型</param>
    /// <returns>外側の型</returns>
    private static List<INamedTypeSymbol> Containers(INamedTypeSymbol type)
    {
        var containers = new List<INamedTypeSymbol>();
        for (var container = type.ContainingType; container is not null; container = container.ContainingType)
            containers.Insert(0, container);

        return containers;
    }

    /// <summary>外側の型が全て partial かの判定</summary>
    /// <param name="type">入れ子の型</param>
    /// <returns>外側の型の全ての宣言が partial なら true</returns>
    internal static bool AllContainersArePartial(INamedTypeSymbol type) =>
        Containers(type).All(container => container.DeclaringSyntaxReferences
            .Select(reference => reference.GetSyntax())
            .OfType<TypeDeclarationSyntax>()
            .All(syntax => syntax.Modifiers.Any(SyntaxKind.PartialKeyword)));

    /// <summary>partial 宣言の型の種類の keyword</summary>
    /// <param name="type">宣言する型</param>
    /// <returns>class、struct、record、record struct、interface のいずれか</returns>
    private static string Keyword(INamedTypeSymbol type) => (type.IsRecord, type.TypeKind) switch
    {
        (true, TypeKind.Struct) => "record struct",
        (true, _) => "record",
        (false, TypeKind.Struct) => "struct",
        (false, TypeKind.Interface) => "interface",
        _ => "class",
    };

    /// <summary>型引数を含む型の宣言名</summary>
    /// <param name="type">宣言する型</param>
    /// <returns>型引数の並びを含む名前</returns>
    private static string Name(INamedTypeSymbol type) =>
        type.TypeParameters.IsEmpty ? Escape(type.Name) : $"{Escape(type.Name)}<{string.Join(", ", type.TypeParameters.Select(parameter => Escape(parameter.Name)))}>";

    /// <summary>コンストラクタの宣言のアクセシビリティ</summary>
    /// <param name="constructor">コンストラクタ</param>
    /// <returns>宣言に書くアクセシビリティの keyword</returns>
    private static string Accessibility(IMethodSymbol constructor) => SyntaxFacts.GetText(constructor.DeclaredAccessibility);

    /// <summary>keyword と衝突する識別子の escape</summary>
    /// <param name="identifier">識別子</param>
    /// <returns>keyword なら @ を付けた識別子</returns>
    private static string Escape(string identifier) =>
        SyntaxFacts.GetKeywordKind(identifier) == SyntaxKind.None ? identifier : "@" + identifier;
}

/// <summary>生成する union の source</summary>
/// <param name="HintName">生成 source の hint 名</param>
/// <param name="Text">生成 source</param>
internal sealed record GeneratedUnion(string HintName, string Text);

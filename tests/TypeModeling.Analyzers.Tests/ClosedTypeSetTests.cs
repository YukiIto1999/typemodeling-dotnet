using TUnit.Assertions;
using TUnit.Assertions.Extensions;
using TUnit.Core;
using static TypeModeling.Analyzers.Tests.ClosedTypeDiagnosticFixture;
using static TypeModeling.Analyzers.Tests.ExhaustivenessAssertions;

namespace TypeModeling.Analyzers.Tests;

/// <summary>閉じた型として網羅を判定する型の範囲</summary>
public sealed class ClosedTypeSetTests
{
    /// <summary>入れ子の閉じた階層の宣言</summary>
    private const string Shapes = """
        using TypeModeling.Domain;

        namespace Probe;

        [Closed]
        public abstract record Shape;
        [Closed]
        public abstract record Polygon : Shape;
        public sealed record Triangle : Polygon;
        public sealed record Square : Polygon;
        public sealed record Circle : Shape;

        public abstract record Animal;
        public sealed record Cat : Animal;
        public sealed record Dog : Animal;

        public enum Light
        {
            Red,
            Green,
        }
        """;

    /// <summary>Closed 属性のない型の、派生や member を尽くしても網羅にならないこと</summary>
    /// <param name="input">switch 式の入力の型と名前</param>
    /// <param name="arms">switch 式の arm</param>
    [Test]
    [Arguments("Animal animal", "Cat => 1, Dog => 2")]
    [Arguments("Light light", "Light.Red => 1, Light.Green => 2")]
    public Task Types_without_the_closed_attribute_are_open(string input, string arms) => AssertNotExhaustive(Shapes + $$"""
        internal static class Handler
        {
            internal static int Describe({{input}}) => {{input.Split(' ')[1]}} switch { {{arms}} };
        }
        """);

    /// <summary>制約の並びを問わず、最も派生した閉じた class に制約された型引数の網羅</summary>
    /// <param name="constraints">型引数の制約の並び</param>
    [Test]
    [Arguments("U, V")]
    [Arguments("V, U")]
    public Task Type_parameters_take_the_most_derived_closed_constraint(string constraints) => AssertExhaustive(Shapes + $$"""
        internal static class Handler
        {
            internal static int Corners<T, U, V>(T shape)
                where T : {{constraints}}
                where U : Shape
                where V : Polygon => shape switch
            {
                Triangle => 3,
                Square => 4,
            };
        }
        """);

    /// <summary>公開の閉じた class ごとの、直接の派生の数を残す assembly 属性</summary>
    [Test]
    public async Task Public_closed_classes_record_their_direct_subtype_counts()
    {
        var generated = SubtypeCountSource("""
            using TypeModeling.Domain;

            [Closed]
            public abstract record Root;
            public sealed record RootLeaf : Root;

            namespace Lib
            {
                [Closed]
                public abstract record Outcome<TValue, TFailure>
                {
                    private Outcome() { }
                    public sealed record Succeeded(TValue Value) : Outcome<TValue, TFailure>;
                    public sealed record Failed(TFailure Failure) : Outcome<TValue, TFailure>;
                    internal sealed record Hidden : Outcome<TValue, TFailure>;
                }

                public static class Holder
                {
                    [Closed]
                    public abstract record @class;
                    public sealed record Only : @class;
                }

                internal static class Internal
                {
                    [Closed]
                    public abstract record Invisible;
                }

                [Closed]
                internal abstract record InternalClosed;

                public abstract record Open;
                public sealed record OpenLeaf : Open;
            }
            """);

        await Assert.That(generated.ReplaceLineEndings("\n")).IsEqualTo("""
            // <auto-generated/>
            [assembly: global::TypeModeling.Domain.ClosedSubtypeCount(typeof(global::Lib.Holder.@class), 1)]
            [assembly: global::TypeModeling.Domain.ClosedSubtypeCount(typeof(global::Lib.Outcome<,>), 3)]
            [assembly: global::TypeModeling.Domain.ClosedSubtypeCount(typeof(global::Root), 1)]

            """);
    }
}

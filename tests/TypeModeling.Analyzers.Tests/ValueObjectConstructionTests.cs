using TUnit.Assertions;
using TUnit.Assertions.Extensions;
using TUnit.Core;
using static TypeModeling.Analyzers.Tests.ValueObjectConstructionFixture;
using static TypeModeling.Analyzers.Tests.ValueObjectSources;

namespace TypeModeling.Analyzers.Tests;

/// <summary>値オブジェクトを new で構築する式の検出</summary>
public sealed class ValueObjectConstructionTests
{
    /// <summary>公開 factory が生成された private コンストラクタで Guid.Empty の値オブジェクトを作る経路の遮断</summary>
    [Test]
    public async Task A_public_factory_cannot_build_a_value_object_from_Guid_Empty()
    {
        var (result, flagged) = await Analyze(
            """
            using TypeModeling.Domain;

            namespace Probe;

            public sealed record OrderIdFailure;

            [ValueObject<System.Guid>]
            public sealed partial record OrderId
            {
                public static OrderId Empty => new(System.Guid.Empty);

                private static Result<System.Guid, OrderIdFailure> Parse(System.Guid raw) => throw null!;
            }
            """
        );

        await Assert.That(result.GeneratedSources.Length).IsEqualTo(1);
        await Assert.That(flagged).IsEquivalentTo(["new(System.Guid.Empty)"]);
    }

    /// <summary>明示と target-typed の new、lambda、field 初期化子、入れ子の型の中の new の検出</summary>
    [Test]
    public async Task Every_new_of_the_value_object_in_source_is_rejected()
    {
        var (result, flagged) = await Analyze(
            Declare(
                SealedPositive,
                """
                private static readonly Positive Field = new(2);
                public static Positive Explicit => new Positive(0);
                public static Positive TargetTyped => new(1);
                public static System.Func<Positive> Factory => () => new Positive(3);
                private static class Helper
                {
                    public static Positive Make() => new Positive(4);
                }
                """
            )
        );

        await Assert.That(result.GeneratedSources.Length).IsEqualTo(1);
        await Assert
            .That(flagged)
            .IsEquivalentTo([
                "new(2)",
                "new Positive(0)",
                "new(1)",
                "new Positive(3)",
                "new Positive(4)",
            ]);
    }

    /// <summary>別の generator が同じ partial 型へ足した factory の new の検出</summary>
    [Test]
    public async Task A_factory_added_to_the_partial_by_another_generator_is_rejected()
    {
        var (result, flagged) = await Analyze(
            Declare(SealedPositive),
            """
            namespace Probe;

            public sealed partial record Positive
            {
                public static Positive Make(int raw) => new Positive(raw);
            }
            """
        );

        await Assert
            .That(
                result.GeneratedSources.Any(generated =>
                    generated.HintName == "Positive.ValueObject.g.cs"
                )
            )
            .IsTrue();
        await Assert.That(flagged).IsEquivalentTo(["new Positive(raw)"]);
    }

    /// <summary>generated の印を付けた手書きの code の factory の new の検出</summary>
    [Test]
    public async Task A_hand_written_factory_marked_as_generated_is_rejected()
    {
        var (result, flagged) = await Analyze(
            "// <auto-generated/>\n"
                + Declare(
                    SealedPositive,
                    "public static Positive Make(int raw) => new Positive(raw);"
                )
        );

        await Assert.That(result.GeneratedSources.Length).IsEqualTo(1);
        await Assert.That(flagged).IsEquivalentTo(["new Positive(raw)"]);
    }

    /// <summary>生成する Create と署名が異なる Create の new の検出</summary>
    [Test]
    public async Task A_Create_with_another_signature_is_rejected()
    {
        var (result, flagged) = await Analyze(
            Declare(
                SealedPositive,
                """
                public static Positive Create(string text) => new Positive(text.Length);
                public static Positive Create(int raw, int extra) => new Positive(raw + extra);
                private static class Helper
                {
                    public static Positive Create(int raw) => new Positive(raw);
                }
                """
            )
        );

        await Assert.That(result.GeneratedSources.Length).IsEqualTo(1);
        await Assert
            .That(flagged)
            .IsEquivalentTo([
                "new Positive(text.Length)",
                "new Positive(raw + extra)",
                "new Positive(raw)",
            ]);
    }
}

using Microsoft.CodeAnalysis.CSharp;
using TUnit.Assertions;
using TUnit.Assertions.Extensions;
using TUnit.Core;
using static TypeModeling.Analyzers.Tests.UnionFixture;

namespace TypeModeling.Analyzers.Tests;

/// <summary>union 宣言の形に generator が足す、C# 15 の lowering と同じ member の source</summary>
public sealed class UnionSourceTests
{
    /// <summary>case 型の宣言</summary>
    private const string Cases = """
        using System.Runtime.CompilerServices;

        namespace Probe;

        public sealed record Cat(string Name);
        public sealed record Dog(string Name);

        """;

    /// <summary>入れ子の union 宣言の形</summary>
    private const string Nested = Cases + """
        public static partial class Outer
        {
            [Union]
            public readonly partial struct Pet
            {
                public partial Pet(Cat value);
                public partial Pet(in Dog? @event);
            }
        }
        """;

    /// <summary>C# 14 で足す、Value、union 構築子の本体、暗黙の変換の source</summary>
    [Test]
    public async Task The_generator_adds_the_members_of_the_csharp_15_lowering()
    {
        await Assert.That(GeneratedSource(Nested).ReplaceLineEndings("\n")).Contains("""
            // <auto-generated/>
            #nullable enable
            namespace Probe;
            partial class Outer
            {
            partial struct Pet : global::System.Runtime.CompilerServices.IUnion
            {
                /// <summary>union が持つ case の値</summary>
                public object? Value { get; }

                /// <summary>case の値を持つ union の構築</summary>
                /// <param name="value">union が持つ case の値</param>
                public partial Pet(global::Probe.Cat value) => this.Value = value;

                /// <summary>case の値を持つ union の構築</summary>
                /// <param name="event">union が持つ case の値</param>
                public partial Pet(in global::Probe.Dog? @event) => this.Value = @event;

                /// <summary>C# 15 の union 変換に当たる case の値からの暗黙の変換</summary>
                /// <param name="value">union が持つ case の値</param>
                /// <returns>case の値を持つ union</returns>
                public static implicit operator Pet(global::Probe.Cat value) => new(value);

                /// <summary>C# 15 の union 変換に当たる case の値からの暗黙の変換</summary>
                /// <param name="value">union が持つ case の値</param>
                /// <returns>case の値を持つ union</returns>
                public static implicit operator Pet(global::Probe.Dog? value) => new(value);
            }
            }

            """);
    }

    /// <summary>外側の型の種類ごとの keyword による partial の再宣言</summary>
    [Test]
    public async Task Containers_are_redeclared_with_their_kind()
    {
        const string source = Cases + """
            public partial interface IZone
            {
                public partial record Area
                {
                    public partial record struct Spot
                    {
                        [Union]
                        public readonly partial struct Pet
                        {
                            public partial Pet(Cat value);
                        }
                    }
                }
            }
            """;

        await Assert.That(Errors(await Run(source))).IsEmpty();
        await Assert.That(GeneratedSource(source).ReplaceLineEndings("\n"))
            .Contains("partial interface IZone\n{\npartial record Area\n{\npartial record struct Spot\n{\npartial struct Pet");
    }

    /// <summary>C# 15 以降で、言語の union 変換に任せて暗黙の変換を足さないこと</summary>
    [Test]
    public async Task Csharp_15_gets_no_implicit_conversions()
    {
        var generated = GeneratedSource(Nested, LanguageVersion.Preview);

        await Assert.That(generated).Contains("public partial Pet(global::Probe.Cat value) => this.Value = value;");
        await Assert.That(generated).DoesNotContain("implicit operator");
    }

    /// <summary>generic の型引数を角括弧にした、型ごとの生成 source の file 名</summary>
    [Test]
    public async Task Each_union_gets_a_file_named_after_its_full_name()
    {
        var names = GeneratedFileNames(Nested + """
            [Union]
            public readonly partial struct Box<T>
            {
                public partial Box(T value);
            }
            """);

        await Assert.That(names).Contains("Probe.Outer.Pet.Union.g.cs");
        await Assert.That(names).Contains("Probe.Box[T].Union.g.cs");
    }

    /// <summary>case 型が null を取りうる場合だけの、nullable な Value</summary>
    /// <param name="declaration">union 宣言の型の名前と制約</param>
    /// <param name="cases">union 構築子の引数</param>
    /// <param name="value">期待する Value の宣言</param>
    [Test]
    [Arguments("Box", "Cat value|Dog value", "public object Value { get; }")]
    [Arguments("Box", "int value|string value", "public object Value { get; }")]
    [Arguments("Box", "int? value|string value", "public object? Value { get; }")]
    [Arguments("Box", "Cat value|Dog? value", "public object? Value { get; }")]
    [Arguments("Box<T>", "T value", "public object? Value { get; }")]
    [Arguments("Box<T> where T : notnull", "T value", "public object Value { get; }")]
    [Arguments("Box<T> where T : struct", "T value", "public object Value { get; }")]
    public async Task Value_is_nullable_only_when_a_case_can_be_null(string declaration, string cases, string value)
    {
        var name = new string([.. declaration.TakeWhile(char.IsLetter)]);
        var constructors = cases.Split('|').Aggregate("", (text, parameter) => text + $"public partial {name}({parameter});\n");
        var generated = GeneratedSource(Cases + $$"""
            [Union]
            public readonly partial struct {{declaration}}
            {
                {{constructors}}
            }
            """);

        await Assert.That(generated).Contains(value);
    }
}
